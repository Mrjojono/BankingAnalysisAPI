type TxnType = 'DEPOSIT' | 'WITHDRAWAL' | 'MERCHANT_PAYMENT' | 'INTERNAL_TRANSFER';
type TxnDef = { desc: string; amount: number; type: TxnType; month: number; day: number };

function randomBetween(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function randomDate2026(month: number, day: number): Date {
  const d = new Date(2026, month - 1, day);
  d.setHours(randomBetween(7, 20), randomBetween(0, 59), 0, 0);
  return d;
}

